"""Structural guarantees for the docs tree.

These are the rules the docs reorganization is held to. They are cheap and
mechanical on purpose: the failure mode being prevented is a page that exists
but cannot be found, or a reader-facing page that leaks internal bookkeeping.
"""

from __future__ import annotations

import re
import subprocess
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[1]
DOCS = REPO_ROOT / "docs"
INDEX = DOCS / "index.md"

#: Pages written for a reader deciding whether to use athenaeum, or trying to
#: operate it. Issue numbers are historical bookkeeping and do not belong here.
#: ``reference/configuration.md`` (issue athenaeum#1424) is GENERATED by
#: ``scripts/gen_config_reference.py``, which strips issue references from
#: every docstring it pulls in — its section headings are the resolver names
#: themselves, carrying no issue ids at all, so it belongs here like any
#: other reader-facing page.
READER_FACING = (
    REPO_ROOT / "README.md",
    INDEX,
    DOCS / "guides",
    DOCS / "modules",
    DOCS / "reference" / "configuration.md",
)

_MD_LINK = re.compile(r"\]\((?!https?:|mailto:|#)([^)#\s]+\.md)")
_ISSUE_REF = re.compile(r"athenaeum#\d+")
#: Real people must not appear as example data in a public repo.
_OPERATOR_NAMES = re.compile(r"\bTristan\b|\btristankromer\b|\bAmanda\b", re.IGNORECASE)

#: The one page allowed to show a package-install command (athenaeum#2300).
#: Every other reader-facing page must link here instead of repeating one.
INSTALL_CANONICAL_PAGE = DOCS / "guides" / "install.md"

#: The README is the front door and must show the install line before
#: ``athenaeum init`` (the release-candidate review found a Quick start with no
#: install command). It is exempt from the no-command rule below, but must not
#: drift: every install command it shows has to appear verbatim in the
#: canonical page (``TestReadmeInstallMatchesCanonicalPage``).
README = REPO_ROOT / "README.md"

#: Every guide, minus the canonical page itself -- the set a stray install
#: command is not allowed to appear in.
_INSTALL_COMMAND_SCAN_TARGETS = tuple(
    p
    for p in sorted((DOCS / "guides").glob("*.md"))
    if p != INSTALL_CANONICAL_PAGE
)

#: Matches the install verb, not the package name -- checked against
#: ``athenaeum`` separately so a line that names a different package (or no
#: package at all) is never flagged.
_INSTALL_VERB = re.compile(r"\bpip install\b|\bpython3?\s+-m\s+pip install\b|\buv tool install\b")
#: A contributor-facing editable/dev install (``pip install -e .`` or
#: ``-e ".[dev,vector]"``) is not a user install command and is exempt --
#: CONTRIBUTING.md's dev setup and install.md's own source-checkout section
#: both use this flag deliberately.
_EDITABLE_INSTALL_FLAG = re.compile(r"(?:^|\s)-e(?:\s|$)")


def _install_command_lines(text: str) -> list[str]:
    """Lines that run a real ``athenaeum`` package install.

    Split each line on ``#``/``&&``/``;`` before checking, so a line that
    pairs a real install with an editable one in the same breath (e.g.
    ``pip install athenaeum   # or: pip install -e . from a checkout``)
    still flags the non-editable half instead of the editable flag
    anywhere on the line hiding both.
    """
    hits: list[str] = []
    for lineno, line in enumerate(text.splitlines(), 1):
        for segment in re.split(r"#|&&|;", line):
            if not _INSTALL_VERB.search(segment):
                continue
            if _EDITABLE_INSTALL_FLAG.search(segment):
                continue
            if "athenaeum" not in segment.lower():
                continue
            hits.append(f"{lineno}: {line.strip()}")
            break
    return hits


def _markdown_files(target: Path) -> list[Path]:
    if target.is_file():
        return [target]
    return sorted(target.rglob("*.md"))


def _reader_facing_files() -> list[Path]:
    out: list[Path] = []
    for t in READER_FACING:
        out.extend(_markdown_files(t))
    return out


def _all_docs_pages() -> list[Path]:
    """Every *tracked* page under ``docs/``, index excepted.

    Tracked, not merely present: a page excluded from version control is not
    part of the published corpus, so the index cannot be faulted for omitting
    it.
    """
    listed = subprocess.run(
        ["git", "ls-files", "-z", "docs"],
        cwd=REPO_ROOT,
        capture_output=True,
        text=True,
        check=True,
    ).stdout.split("\0")
    return sorted(
        REPO_ROOT / rel
        for rel in listed
        if rel.endswith(".md") and not rel.endswith("/index.md")
    )


class TestLinksResolve:
    """Every relative markdown link in the tree points at a file that exists."""

    def test_every_relative_link_in_docs_resolves(self) -> None:
        broken: list[str] = []
        for page in sorted(DOCS.rglob("*.md")):
            for lineno, line in enumerate(page.read_text(encoding="utf-8").splitlines(), 1):
                for m in _MD_LINK.finditer(line):
                    target = m.group(1)
                    base = REPO_ROOT if target.startswith("docs/") else page.parent
                    if not (base / target).resolve().exists():
                        rel = page.relative_to(REPO_ROOT)
                        broken.append(f"{rel}:{lineno} -> {target}")
        assert not broken, "broken relative links:\n  " + "\n  ".join(broken)

    def test_every_relative_link_in_root_markdown_resolves(self) -> None:
        broken: list[str] = []
        for name in ("README.md", "CONTRIBUTING.md", "AGENTS.md"):
            page = REPO_ROOT / name
            if not page.exists():
                continue
            for lineno, line in enumerate(page.read_text(encoding="utf-8").splitlines(), 1):
                for m in _MD_LINK.finditer(line):
                    if not (REPO_ROOT / m.group(1)).resolve().exists():
                        broken.append(f"{name}:{lineno} -> {m.group(1)}")
        assert not broken, "broken relative links:\n  " + "\n  ".join(broken)


class TestIndexIsComplete:
    """No page is unreachable from the index.

    This is the acceptance criterion the reorganization exists to satisfy: the
    corpus was never short on content, only on any way to find it.
    """

    def test_index_exists(self) -> None:
        assert INDEX.exists(), "docs/index.md is the map; it must exist"

    def test_every_docs_page_is_linked_from_the_index(self) -> None:
        text = INDEX.read_text(encoding="utf-8")
        linked = {
            (INDEX.parent / m.group(1)).resolve()
            for m in _MD_LINK.finditer(text)
        }
        missing = [
            str(p.relative_to(REPO_ROOT))
            for p in _all_docs_pages()
            if p.resolve() not in linked
        ]
        assert not missing, (
            "these pages exist but are unreachable from docs/index.md:\n  "
            + "\n  ".join(missing)
        )


class TestReaderFacingHygiene:
    """Reader-facing pages carry no internal bookkeeping."""

    @pytest.mark.parametrize(
        "page", _reader_facing_files(), ids=lambda p: str(p.relative_to(REPO_ROOT))
    )
    def test_no_issue_references(self, page: Path) -> None:
        hits = [
            f"{lineno}: {line.strip()}"
            for lineno, line in enumerate(page.read_text(encoding="utf-8").splitlines(), 1)
            if _ISSUE_REF.search(line)
        ]
        assert not hits, (
            f"{page.relative_to(REPO_ROOT)} cites issue numbers; nobody reading the "
            "docs needs the historical record:\n  " + "\n  ".join(hits)
        )

    @pytest.mark.parametrize(
        "page", _reader_facing_files(), ids=lambda p: str(p.relative_to(REPO_ROOT))
    )
    def test_no_operator_names_in_examples(self, page: Path) -> None:
        hits = [
            f"{lineno}: {line.strip()}"
            for lineno, line in enumerate(page.read_text(encoding="utf-8").splitlines(), 1)
            if _OPERATOR_NAMES.search(line)
        ]
        assert not hits, (
            f"{page.relative_to(REPO_ROOT)} names a real person; use the example cast "
            "(Jordan Reyes, Priya Raman, Acme Corp):\n  " + "\n  ".join(hits)
        )


class TestModulePagesAnswerTheFourQuestions:
    """Every module page answers the same four questions, in the same order.

    A module page exists to say what a component refuses. That section is the
    one readers currently have to infer, so it is the one worth enforcing.
    """

    REQUIRED = ("## What it does", "## What it reads", "## What it writes", "## What it refuses")

    @pytest.mark.parametrize(
        "page",
        sorted((DOCS / "modules").glob("*.md")),
        ids=lambda p: p.name,
    )
    def test_has_the_four_headings_in_order(self, page: Path) -> None:
        text = page.read_text(encoding="utf-8")
        positions = []
        for heading in self.REQUIRED:
            idx = text.find(heading)
            assert idx != -1, f"{page.name} is missing '{heading}'"
            positions.append(idx)
        assert positions == sorted(positions), (
            f"{page.name} has the four sections out of order"
        )

    @pytest.mark.parametrize(
        "page",
        sorted((DOCS / "modules").glob("*.md")),
        ids=lambda p: p.name,
    )
    def test_has_a_see_also_block(self, page: Path) -> None:
        assert "## See also" in page.read_text(encoding="utf-8"), (
            f"{page.name} must cross-link its guide, design record, and siblings"
        )


class TestGuidesAndModulesCrossLink:
    """A guide and its module page point at each other.

    They answer different questions about the same component -- the guide says
    *do this*, the module page says *what it reads, writes and refuses* -- and
    they drift apart the moment neither names the other.
    """

    @pytest.mark.parametrize(
        "page", sorted((DOCS / "modules").glob("*.md")), ids=lambda p: p.name
    )
    def test_module_see_also_names_a_guide(self, page: Path) -> None:
        see_also = page.read_text(encoding="utf-8").partition("## See also")[2]
        assert "../guides/" in see_also, (
            f"{page.name} has no guide in its See also block"
        )

    @pytest.mark.parametrize(
        "page", sorted((DOCS / "guides").glob("*.md")), ids=lambda p: p.name
    )
    def test_guide_opens_with_a_reference_pointer(self, page: Path) -> None:
        head = "".join(page.read_text(encoding="utf-8").splitlines(keepends=True)[:8])
        assert "**Reference:**" in head and "../modules/" in head, (
            f"{page.name} must open with a **Reference:** line naming its module page(s)"
        )


class TestReadmeInstallMatchesCanonicalPage:
    """README's Quick start shows an install line, and it matches install.md."""

    def test_readme_install_lines_appear_in_the_canonical_page(self) -> None:
        readme_lines = [
            line.split(": ", 1)[1]
            for line in _install_command_lines(README.read_text(encoding="utf-8"))
        ]
        assert readme_lines, "README's Quick start must show an install command"
        canonical = INSTALL_CANONICAL_PAGE.read_text(encoding="utf-8")
        missing = [line for line in readme_lines if line not in canonical]
        assert not missing, (
            "README shows an install command install.md does not:\n  "
            + "\n  ".join(missing)
        )

    def test_install_precedes_init_in_quick_start(self) -> None:
        text = README.read_text(encoding="utf-8")
        quick = text.partition("## Quick start")[2]
        assert 0 <= quick.find("uv tool install") < quick.find("athenaeum init")


class TestOneCanonicalInstallPage:
    """Exactly one page may show a package-install command (athenaeum#2300).

    Before the uv-first install work (athenaeum#2297), README, install.md,
    claude-code.md, and sidecar.md each carried their own install command and
    they drifted out of sync with each other. ``install.md`` is now the one
    place a ``pip install athenaeum`` / ``uv tool install ... athenaeum``
    line may live; every other guide must link to it instead of repeating
    the command, so there is nothing left to drift.

    ``CONTRIBUTING.md`` and ``CHANGELOG.md`` are deliberately not scanned:
    CONTRIBUTING's dev-setup ``pip install -e ".[dev,vector]"`` is a
    contributor editable install, not a user install command (and that
    whole class is exempt everywhere, not just there -- see
    ``_EDITABLE_INSTALL_FLAG``), and CHANGELOG.md is a historical record,
    not an operating guide. ``docs/guides/upgrading.md`` was checked by hand
    and carries no install command at all, so it needs no exemption either.
    """

    @pytest.mark.parametrize(
        "page",
        _INSTALL_COMMAND_SCAN_TARGETS,
        ids=lambda p: str(p.relative_to(REPO_ROOT)),
    )
    def test_no_install_command_outside_canonical_page(self, page: Path) -> None:
        hits = _install_command_lines(page.read_text(encoding="utf-8"))
        assert not hits, (
            f"{page.relative_to(REPO_ROOT)} repeats a package-install command; "
            f"link to {INSTALL_CANONICAL_PAGE.relative_to(REPO_ROOT)} instead:\n  "
            + "\n  ".join(hits)
        )

    def test_canonical_page_itself_still_holds_install_commands(self) -> None:
        """Sanity check on the exemption, not a scan of the real tree.

        If a future edit emptied install.md of its own commands, the test
        above would pass vacuously (nothing left to find anywhere) while the
        acceptance criterion silently broke. Pin that install.md actually is
        where the commands live.
        """
        hits = _install_command_lines(INSTALL_CANONICAL_PAGE.read_text(encoding="utf-8"))
        assert hits, (
            f"{INSTALL_CANONICAL_PAGE.relative_to(REPO_ROOT)} is supposed to be the "
            "one page holding install commands, but none were found there"
        )

    def test_detector_fires_on_a_synthetic_fixture_page(self, tmp_path: Path) -> None:
        """The detector flags its own counter-example (athenaeum#2300's AC2).

        A test that only scans the real docs tree would pass identically
        whether the detector works or is silently broken, because the tree
        is already clean -- this synthetic page is the positive control
        that proves the regex itself still fires, independent of the real
        corpus's current state.
        """
        fixture = tmp_path / "fixture-page.md"
        fixture.write_text(
            "# Fixture\n\nJust run:\n\n```bash\npip install athenaeum\n```\n",
            encoding="utf-8",
        )
        hits = _install_command_lines(fixture.read_text(encoding="utf-8"))
        assert hits, "detector failed to flag `pip install athenaeum` in a fixture page"

    def test_detector_fires_on_realistic_variants(self, tmp_path: Path) -> None:
        variants = [
            "pip install athenaeum",
            "pip install 'athenaeum[mcp]'",
            'pip install "athenaeum[vector]"',
            "python -m pip install athenaeum",
            "python3 -m pip install athenaeum",
            "uv tool install --python 3.13 athenaeum",
            "uv tool install --python 3.13 'athenaeum[mcp]'",
        ]
        for variant in variants:
            fixture = tmp_path / "fixture-page.md"
            fixture.write_text(f"```bash\n{variant}\n```\n", encoding="utf-8")
            hits = _install_command_lines(fixture.read_text(encoding="utf-8"))
            assert hits, f"detector failed to flag variant: {variant!r}"

    def test_detector_allows_an_editable_dev_install(self, tmp_path: Path) -> None:
        fixture = tmp_path / "fixture-page.md"
        fixture.write_text(
            '```bash\npip install -e ".[dev,vector]"\n```\n', encoding="utf-8"
        )
        hits = _install_command_lines(fixture.read_text(encoding="utf-8"))
        assert not hits, "an editable/dev install must not be flagged"

    def test_detector_catches_a_real_install_hiding_behind_an_editable_comment(
        self, tmp_path: Path
    ) -> None:
        """A non-editable install must not escape detection by sharing a line
        with an editable one -- this is the exact shape ``sidecar.md`` had
        before this fix (athenaeum#2300)."""
        fixture = tmp_path / "fixture-page.md"
        fixture.write_text(
            "```bash\npip install athenaeum   # or: pip install -e . from a checkout\n```\n",
            encoding="utf-8",
        )
        hits = _install_command_lines(fixture.read_text(encoding="utf-8"))
        assert hits, "a real install sharing a line with an editable one must still be flagged"
